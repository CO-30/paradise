const WEEK_MS = 7 * 24 * 3600 * 1000;
export function weeklyTheme(date = new Date()) {
  const week = Math.floor((date.getTime() + 3 * 24 * 3600 * 1000) / WEEK_MS); // 月曜始まり
  return { week, card: CARD_ORDER[week % CARD_ORDER.length], activity: WEEKLY[week % WEEKLY.length] };
}

export function season(date = new Date()) {
  const m = date.getMonth() + 1;
  return m >= 3 && m <= 5 ? 'spring' : m >= 6 && m <= 8 ? 'summer' : m >= 9 && m <= 11 ? 'autumn' : 'winter';
}
